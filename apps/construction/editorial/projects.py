def href(path=""):
    return BASE + path.strip("/") + ("/" if path.strip("/") else "")


def photo(path, alt, eager=False):
    load = 'loading="eager" fetchpriority="high"' if eager else 'loading="lazy"'
    return f'<img src="{BASE}{escape(path)}" alt="{escape(alt)}" {load} decoding="async">'


def crumbs(label, parent=None):
    links = [f'<a href="{BASE}">Главная</a>']
    if parent:
        links.append(f'<a href="{href(parent[0])}">{escape(parent[1])}</a>')
    links.append(f'<span aria-current="page">{escape(label)}</span>')
    return '<nav class="breadcrumbs" aria-label="Навигационная цепочка">' + ' <span aria-hidden="true">/</span> '.join(links) + '</nav>'


def intro(title, description):
    return f'<header class="page-intro work-intro"><h1 class="display">{escape(title)}</h1><p class="lead">{escape(description)}</p></header>'


def tile(slug, project, eager=False):
    return f'''<a class="tile work-tile" data-group="{project['group']}" href="{href("projects/" + slug)}">
  <figure>{photo(project["cover"], project["alt"], eager)}</figure>
  <div class="tile-copy"><span class="work-category">{escape(project["kind"])}</span><h2>{escape(project["name"])}</h2><p>{escape(project["lead"])}</p></div>
</a>'''


def projects_index():
    groups = [("all", "Все"), ("housing", "Жильё"), ("industry", "Промышленность"),
              ("business", "Деловые здания"), ("infra", "Инфраструктура")]
    filters = "".join(
        f'<button type="button" data-choice="{key}" aria-pressed="{str(key == "all").lower()}" aria-controls="work-projects">{label}</button>'
        for key, label in groups
    )
    cards = "".join(tile(slug, item, index == 0) for index, (slug, item) in enumerate(PROJECTS.items()))
    return f'''<div class="work-page shell">
{crumbs("Проекты")}
{intro("Проекты", "Пять проектных концепций. Откройте объект, чтобы посмотреть, как рельеф, технология и будущая эксплуатация определяют строительные решения.")}
<div class="tocbar work-filters" role="group" aria-label="Тип проекта" hidden>{filters}<span class="work-sr" role="status" aria-live="polite"></span></div>
<div class="tiles work-tiles" id="work-projects">{cards}</div>
</div>'''


def facts(rows):
    items = "".join(f"<div><dt>{escape(label)}</dt><dd>{escape(value)}</dd></div>" for label, value in rows)
    return f'<dl class="facts work-facts">{items}</dl>'


def narrative(title, text):
    return f'<section class="detail-grid work-detail-grid"><div><h2>{escape(title)}</h2></div><div><p>{escape(text)}</p></div></section>'


def related(path, title, action):
    return f'<section class="section work-next"><h2>{escape(title)}</h2><a class="text-link" href="{href(path)}">{escape(action)}</a></section>'


def project_page(project):
    service_slug = project["service"]
    cover = photo(project["cover"], project["alt"], eager=True)
    detail = photo(project["detail"], project["caption"].split(".")[0])
    return f'''<div class="work-page shell">
{crumbs(project["name"], ("projects", "Проекты"))}
{intro(project["name"], project["lead"])}
<figure class="poster work-poster">{cover}<figcaption>Проектная концепция · {escape(project["kind"])}</figcaption></figure>
{facts([("Тип объекта", project["kind"]), ("Состав", project["subject"]), ("Инженерный акцент", project["focus"])])}
{narrative("Задача", project["task"])}
{narrative("Решение", project["solution"])}
<figure class="work-figure">{detail}<figcaption>{escape(project["caption"])}</figcaption></figure>
{narrative(project["extra"], project["extra_text"])}
{related("directions/" + service_slug, SERVICES[service_slug]["name"], "О направлении")}
</div>'''


