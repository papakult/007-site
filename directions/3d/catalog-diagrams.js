export function hasMechanismDiagram(id) {
  return Object.hasOwn(diagrams,id);
}

export function mechanismDiagram(id,model,openView) {
  const entry=diagrams[id];
  if(!entry)return null;
  const [title,steps,source]=entry;
  const details=document.createElement('details');
  details.className='model-inspector model-diagram';
  const summary=document.createElement('summary');
  summary.textContent='Схема устройства';
  const heading=document.createElement('h3');
  heading.textContent=title;
  const list=document.createElement('ol');
  for(const [label,detail,viewLabel] of steps){
    const item=document.createElement('li');
    const view=model.views?.find(candidate=>candidate.label===viewLabel);
    const caption=document.createElement(view?'button':'strong');
    caption.textContent=label;
    if(view){
      caption.type='button';
      caption.addEventListener('click',()=>openView(model,view));
    }
    const explanation=document.createElement('p');
    explanation.textContent=detail;
    item.append(caption,explanation);list.append(item);
  }
  details.append(summary,heading);
  if(graphics[id]){
    const figure=document.createElement('div');
    figure.className='model-diagram-graphic';
    figure.innerHTML=graphics[id];
    details.append(figure);
  }
  details.append(list);
  if(source){
    const link=document.createElement('a');
    link.href=source[1];
    link.className='model-open';
    link.textContent=source[0];
    details.append(link);
  }
  return details;
}
